# Day 2 - Variables and Comments

# A variable stores a value.
name = "Koushik"
age = 22
course = "Python"

print("Name:", name)
print("Age:", age)
print("Course:", course)

# Multiple assignment
x, y, z = 10, 20, 30
print(x, y, z)

# Reassignment
age = 23
print("Updated age:", age)

# Swapping variables
x, y = y, x
print("After swapping:", x, y)

# Deleting a variable
temp = 100
del temp

